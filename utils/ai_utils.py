def estimate_min_duration_and_plan(
    goal: str,
    current_level: str = "",
    target_level: str = "",
    minutes_per_day: int = 30
) -> Union[int, Tuple[int, List[str]]]:
    """
    Оценивает минимально возможный срок достижения цели для среднего человека
    с учётом доступного времени в день.
    Если цель недостижима, возвращает 0.
    Иначе возвращает кортеж (минимальное_количество_дней, список_строк_расписания).
    """
    prompt = f"""
Ты — эксперт по планированию. Твоя задача — оценить минимально возможный срок достижения цели для среднего человека, учитывая доступное время в день, и составить пошаговое расписание.

Входные данные:
Цель: {goal}
Текущий уровень: {current_level}
Желаемый уровень: {target_level}
Время в день (минут): {minutes_per_day}

Правила:
1. Если цель НЕДОСТИЖИМА для среднего человека даже при максимальных усилиях (например, выучить китайский за день), ответь только числом 0. Никаких других слов.
2. Если цель достижима, определи минимальное целое количество дней, необходимое для её достижения при указанном времени в день. Используй реалистичные средние показатели прогресса.
3. Затем составь расписание действий на каждый день, когда нужно что-то делать. Дни без действий (например, отдых) не включай.
4. Нумерация дней сквозная от начала проекта (День 1, День 2, День 3, ...). Если нужны дни отдыха, пропускай номера (например, День 1, День 3, День 5).
5. Каждая строка расписания должна начинаться с "День N:" и содержать конкретное действие. Никаких пояснений до и после расписания.
6. ОТВЕТ ДОЛЖЕН СТРОГО СООТВЕТСТВОВАТЬ ФОРМАТУ:
   - Первая строка: только число (минимальный срок).
   - Вторая строка: пустая.
   - Все последующие строки: расписание, каждая строка с новой строки.

Пример 1 (достижимо):
Цель: научиться подтягиваться 30 раз
Текущий уровень: 5 раз
Желаемый уровень: 30 раз
Время в день: 30 минут

Ответ:
45

День 1: Разминка, 3 подхода с максимальным количеством подтягиваний.
День 3: Негативные подтягивания 4x5.
День 5: Лёгкая тренировка хвата и кора.
... (и так далее до дня 45)

Пример 2 (недостижимо):
Цель: научиться подтягиваться 100 раз за месяц
Текущий уровень: 0 раз
Время в день: 10 минут

Ответ:
0

Теперь выполни задание для указанных входных данных. Помни: никаких лишних слов, только число, пустая строка и расписание.
"""
    response = client.models.generate_content(
        model="gemini-3-flash-preview",
        contents=prompt
    )
    text = response.text.strip()

    # Если ответ состоит только из цифр (возможно с пробелами)
    if text.isdigit():
        return int(text)

    # Пытаемся найти число в первой строке
    lines = text.split('\n')
    first_line = lines[0].strip() if lines else ""
    match = re.match(r'^(\d+)$', first_line)
    if match:
        min_days = int(match.group(1))
        # Остальные строки — расписание (пропускаем вторую пустую строку)
        schedule = []
        for line in lines[1:]:
            line = line.strip()
            if line and line.lower().startswith('день'):
                schedule.append(line)
        if schedule:
            return (min_days, schedule)
        else:
            # Если после числа нет расписания, считаем ошибкой
            return 0
    else:
        # Если первая строка не число, возможно модель сразу начала с расписания
        # Попробуем найти число где-то ещё
        numbers = re.findall(r'^\d+$', text, re.MULTILINE)
        if numbers:
            min_days = int(numbers[0])
            # Удаляем найденное число из текста
            rest = re.sub(r'^\d+\s*\n?', '', text, count=1, flags=re.MULTILINE).strip()
            lines = rest.split('\n')
            schedule = [line.strip() for line in lines if line.strip() and line.strip().lower().startswith('день')]
            if schedule:
                return (min_days, schedule)
        # Если ничего не получилось, возвращаем 0 (невозможно определить)
        return 0